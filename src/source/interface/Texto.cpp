int Texto::largura(const std::string &texto, int escala)
{
    if (texto.empty() || escala < 1)
    {
        return 0;
    }
    const int quantidade = static_cast<int>(texto.size());
    const int colunas = quantidade * LARGURA_GLIFO + (quantidade - 1) * ESPACO_GLIFO;
    return colunas * escala;
}

int Texto::altura(int escala)
{
    if (escala < 1)
    {
        return 0;
    }
    return ALTURA_GLIFO * escala;
}

void Texto::desenhar(SDL_Renderer *renderizador, const std::string &texto, int x, int y, int escala,
                     SDL_Color cor)
{
    if (renderizador == nullptr || texto.empty() || escala < 1)
    {
        return;
    }

    std::vector<SDL_Rect> pixels;
    pixels.reserve(texto.size() * 16);

    int cursor = x;
    for (char c : texto)
    {
        const unsigned char *glifo = FONTE[indice_glifo(c)];

        for (int linha = 0; linha < ALTURA_GLIFO; linha++)
        {
            for (int coluna = 0; coluna < LARGURA_GLIFO; coluna++)
            {
                const int bit = LARGURA_GLIFO - 1 - coluna;
                if ((glifo[linha] >> bit) & 1)
                {
                    SDL_Rect ponto;
                    ponto.x = cursor + coluna * escala;
                    ponto.y = y + linha * escala;
                    ponto.w = escala;
                    ponto.h = escala;
                    pixels.push_back(ponto);
                }
            }
        }
        cursor += (LARGURA_GLIFO + ESPACO_GLIFO) * escala;
    }

    if (pixels.empty())
    {
        return;
    }

    SDL_SetRenderDrawColor(renderizador, cor.r, cor.g, cor.b, cor.a);
    SDL_RenderFillRects(renderizador, pixels.data(), static_cast<int>(pixels.size()));
}

void Texto::desenhar_centralizado(SDL_Renderer *renderizador, const std::string &texto, int centroX,
                                  int y, int escala, SDL_Color cor)
{
    const int x = centroX - Texto::largura(texto, escala) / 2;
    Texto::desenhar(renderizador, texto, x, y, escala, cor);
}
