constexpr int INDICE_ESPACO = 36;

// Converte um caractere no indice da tabela acima; o que nao existe vira espaco.
int indice_glifo(char c)
{
    if (c >= 'a' && c <= 'z')
        c = static_cast<char>(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z')
        return c - 'A';
    if (c >= '0' && c <= '9')
        return 26 + (c - '0');

    switch (c)
    {
    case ' ':
        return INDICE_ESPACO;
    case '.':
        return 37;
    case ':':
        return 38;
    case '-':
        return 39;
    case '!':
        return 40;
    case '?':
        return 41;
    case '/':
        return 42;
    case ',':
        return 43;
    case '+':
        return 44;
    default:
        return INDICE_ESPACO;
    }
}
